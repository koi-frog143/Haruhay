    ('AIR_CONDITIONING', 'Air conditioning'), ('FURNITURE', 'Furniture'),
    ('GENERAL', 'General repair'), ('OTHER', 'Other');

CREATE TABLE maintenance_staff (
    account_id UUID PRIMARY KEY REFERENCES accounts(id),
    property_id UUID NOT NULL REFERENCES properties(id),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NOT NULL REFERENCES accounts(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX maintenance_staff_property ON maintenance_staff(property_id);

CREATE TABLE maintenance_tickets (
    id UUID PRIMARY KEY,
    number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    request_key UUID NOT NULL,
    resident_id UUID NOT NULL REFERENCES accounts(id),
    tenancy_id UUID NOT NULL REFERENCES tenancies(id),
    property_id UUID NOT NULL REFERENCES properties(id),
    room_id UUID NOT NULL REFERENCES rooms(id),
    category VARCHAR(32) NOT NULL REFERENCES maintenance_categories(code),
    description VARCHAR(2000) NOT NULL,
    shared_area BOOLEAN NOT NULL,
    location VARCHAR(200) NOT NULL,
    priority VARCHAR(12) NOT NULL CHECK (priority IN ('ROUTINE','HIGH','CRITICAL')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('SUBMITTED','ASSIGNED','IN_PROGRESS','READY','CLOSED','CANCELLED')),
    version INTEGER NOT NULL DEFAULT 0,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    archived_at TIMESTAMP WITH TIME ZONE,
    UNIQUE(resident_id, request_key)
);
CREATE INDEX maintenance_tickets_property ON maintenance_tickets(property_id, status, submitted_at);
CREATE INDEX maintenance_tickets_resident ON maintenance_tickets(resident_id, submitted_at);

CREATE TABLE maintenance_assignments (
    id UUID PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES maintenance_tickets(id) ON DELETE CASCADE,
    technician_id UUID NOT NULL REFERENCES maintenance_staff(account_id),
    assigned_by UUID NOT NULL REFERENCES accounts(id),
    reason VARCHAR(1000),
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    ended_at TIMESTAMP WITH TIME ZONE,
    active_ticket UUID UNIQUE REFERENCES maintenance_tickets(id) ON DELETE CASCADE,
    CHECK ((ended_at IS NULL AND active_ticket IS NOT NULL AND active_ticket=ticket_id)
        OR (ended_at IS NOT NULL AND active_ticket IS NULL))
);
CREATE INDEX maintenance_assignments_staff ON maintenance_assignments(technician_id, active_ticket);

CREATE TABLE maintenance_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES maintenance_tickets(id) ON DELETE CASCADE,
    actor_id UUID NOT NULL REFERENCES accounts(id),
    kind VARCHAR(24) NOT NULL,
    message VARCHAR(2000),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX maintenance_activity_ticket ON maintenance_activity(ticket_id, id);

CREATE TABLE maintenance_completions (
    activity_id BIGINT PRIMARY KEY REFERENCES maintenance_activity(id) ON DELETE CASCADE,
    assignment_id UUID NOT NULL REFERENCES maintenance_assignments(id) ON DELETE CASCADE,
    materials VARCHAR(500)
);

CREATE TABLE maintenance_photos (
    id UUID PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES maintenance_tickets(id) ON DELETE CASCADE,
    uploaded_by UUID NOT NULL REFERENCES accounts(id),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    content_type VARCHAR(24) NOT NULL,
    content BYTEA NOT NULL
);
CREATE INDEX maintenance_photos_ticket ON maintenance_photos(ticket_id);

CREATE TABLE maintenance_notifications (
    id UUID PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES maintenance_tickets(id) ON DELETE CASCADE,
    recipient_id UUID NOT NULL REFERENCES accounts(id),
    message VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX maintenance_notifications_recipient ON maintenance_notifications(recipient_id, created_at);
