CREATE TABLE holding_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id UUID NOT NULL REFERENCES accounts(id),
 property_id UUID NOT NULL REFERENCES properties(id),
 application_id UUID NOT NULL REFERENCES registration_applications(id),
 tenancy_id UUID NOT NULL REFERENCES tenancies(id),
 category VARCHAR(50) NOT NULL,
 description VARCHAR(150) NOT NULL,
 sender VARCHAR(100) NOT NULL DEFAULT '',
 depositor VARCHAR(30) NOT NULL,
 tracking VARCHAR(100) NOT NULL DEFAULT '',
 slot VARCHAR(10) NOT NULL,
 pickup_pin VARCHAR(6) NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('READY','CLAIMED','DELETED')),
 received_at TIMESTAMP WITH TIME ZONE NOT NULL,
 received_by UUID NOT NULL REFERENCES accounts(id),
 claimed_at TIMESTAMP WITH TIME ZONE,
 claimed_by VARCHAR(100),
 relationship VARCHAR(32),
 id_type VARCHAR(60),
 id_last_four VARCHAR(4),
 receipt_confirmed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX holding_owner_status_received ON holding_items(owner_id,status,received_at);
CREATE INDEX holding_tenancy_status_received ON holding_items(tenancy_id,status,received_at);
CREATE INDEX holding_property_slot_status ON holding_items(property_id,slot,status);

CREATE TABLE holding_item_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES holding_items(id),
 actor_id UUID NOT NULL REFERENCES accounts(id),
 event_type VARCHAR(24) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 details VARCHAR(1000) NOT NULL DEFAULT ''
);
CREATE INDEX holding_transactions_item ON holding_item_transactions(item_id,id);

CREATE TABLE holding_inquiries (
 id UUID PRIMARY KEY,
 owner_id UUID NOT NULL REFERENCES accounts(id),
 actor_id UUID NOT NULL REFERENCES accounts(id),
 visitor_name VARCHAR(100) NOT NULL,
 id_type VARCHAR(60) NOT NULL,
 id_last_four VARCHAR(4) NOT NULL,
 looking_for VARCHAR(220) NOT NULL,
 purpose VARCHAR(100) NOT NULL,
 result VARCHAR(40) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX holding_inquiries_owner_time ON holding_inquiries(owner_id,occurred_at);
