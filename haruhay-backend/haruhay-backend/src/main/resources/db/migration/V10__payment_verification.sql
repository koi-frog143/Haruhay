CREATE TABLE bill_payment_submissions (
    id UUID PRIMARY KEY,
    bill_id UUID NOT NULL REFERENCES monthly_bills(id) ON DELETE CASCADE,
    property_id UUID NOT NULL REFERENCES properties(id),
    request_key UUID NOT NULL,
    corrects_id UUID REFERENCES bill_payment_submissions(id) ON DELETE SET NULL,
    amount DECIMAL(12,2) NOT NULL CHECK(amount>0),
    method VARCHAR(20) NOT NULL CHECK(method IN ('GCASH','BANK_TRANSFER','FRONT_DESK')),
    payment_date DATE NOT NULL,
    reference VARCHAR(120) NOT NULL,
    reference_key VARCHAR(120) NOT NULL,
    active_reference VARCHAR(120),
    status VARCHAR(16) NOT NULL CHECK(status IN ('PENDING','APPROVED','DECLINED','REVERSED')),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(bill_id,request_key),
    UNIQUE(property_id,method,active_reference),
    CHECK ((status='APPROVED' AND active_reference IS NOT NULL AND active_reference=reference_key)
        OR (status<>'APPROVED' AND active_reference IS NULL))
);
CREATE INDEX bill_payments_bill ON bill_payment_submissions(bill_id,submitted_at);
CREATE INDEX bill_payments_reference ON bill_payment_submissions(property_id,method,reference_key);

CREATE TABLE bill_payment_proofs (
    payment_id UUID PRIMARY KEY REFERENCES bill_payment_submissions(id) ON DELETE CASCADE,
    content_type VARCHAR(24) NOT NULL,
    content BYTEA NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE bill_payment_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id UUID NOT NULL REFERENCES bill_payment_submissions(id) ON DELETE CASCADE,
    actor_id UUID NOT NULL REFERENCES accounts(id),
    action VARCHAR(12) NOT NULL CHECK(action IN ('APPROVED','DECLINED','REVERSED')),
    reason VARCHAR(1000),
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(payment_id,action)
);
CREATE TABLE bill_payment_ledger (
    id UUID PRIMARY KEY,
    payment_id UUID NOT NULL REFERENCES bill_payment_submissions(id) ON DELETE CASCADE,
    kind VARCHAR(8) NOT NULL CHECK(kind IN ('PAYMENT','REVERSAL')),
    amount DECIMAL(12,2) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(payment_id,kind),
    CHECK ((kind='PAYMENT' AND amount>0) OR (kind='REVERSAL' AND amount<0))
);
CREATE TABLE bill_payment_receipts (
    payment_id UUID PRIMARY KEY REFERENCES bill_payment_submissions(id) ON DELETE CASCADE,
    number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    property_name VARCHAR(160) NOT NULL,
    resident_name VARCHAR(100) NOT NULL,
    room_label VARCHAR(80) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE VIEW billing_balances AS
    SELECT b.*, b.rent+b.fixed_charges AS total, COALESCE(t.paid,0) AS paid,
        b.rent+b.fixed_charges-COALESCE(t.paid,0) AS balance,
        CASE WHEN COALESCE(t.paid,0)>=b.rent+b.fixed_charges THEN 'PAID'
             WHEN COALESCE(t.paid,0)>0 THEN 'PARTIAL' ELSE 'UNPAID' END AS bill_status
    FROM monthly_bills b
    LEFT JOIN (
        SELECT p.bill_id,SUM(l.amount) AS paid FROM bill_payment_ledger l
        JOIN bill_payment_submissions p ON p.id=l.payment_id GROUP BY p.bill_id
    ) t ON t.bill_id=b.id;
